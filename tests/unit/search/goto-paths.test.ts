// Go to definition derives paths from file contents (composer.json, autoload_psr4.php, import
// specifiers, PHP namespaces): untrusted text from the opened folder. One case per attack: nothing may
// name a file outside the folder or an odd device, whatever the source.
import { describe, expect, it } from 'vitest';
import { safeJoin, safeRel } from '../../../src/search/goto/paths';
import { psr4Candidates, psr4FromAutoload, psr4FromComposer, psr4Index } from '../../../src/search/goto/php';
import { jsCandidates, pyCandidates } from '../../../src/search/goto/js';

describe('safeRel / safeJoin: one case per attack', () => {
  const refused: Array<[string, string]> = [
    ['parent escape', '../etc/passwd'],
    ['escape after a folder', 'app/../../secret.php'],
    ['deep escape', 'a/b/../../../x'],
    ['the root itself', 'a/..'],
    ['absolute POSIX', '/etc/passwd'],
    ['drive letter', 'C:/Windows/win.ini'],
    ['drive-relative', 'C:Windows'],
    ['UNC', '\\\\server\\share\\x.php'],
    ['backslash traversal', 'app\\..\\..\\x.php'],
    ['backslash separator', 'app\\Models\\User.php'],
    ['NUL byte', 'app/User.php\u0000.png'],
    ['control character', 'app/\u0007bell.php'],
    ['newline', 'app/a\nb.php'],
    ['DEL', 'app/\u007f.php'],
    ['alternate data stream', 'app/User.php::$DATA'],
    ['URL scheme', 'file:///etc/passwd'],
    ['Windows device', 'con'],
    ['Windows device with extension', 'app/NUL.php'],
    ['Windows device, trailing dot', 'app/aux.'],
    ['COM port', 'lpt1.txt'],
    ['empty', ''],
    ['only dots', './.'],
    ['too long', 'a/'.repeat(600)],
    ['device, blank before the extension', 'app/con .php'],
    ['device, tab before the extension', 'CON\t.txt'],
    ['device, upper case', 'app/AUX'],
    ['UNC with forward slashes', '//server/share/x.php'],
    ['Win32 device namespace', '\\\\?\\C:\\x'],
    ['trailing dot (Win32 strips it)', 'app/User.php.'],
    ['trailing space', 'app/User.php '],
    ['folder with a trailing dot', 'app./User.php'],
    ['too many segments', Array.from({ length: 65 }, () => 'a').join('/')],
  ];
  for (const [what, p] of refused) it(`refuses ${what}`, () => expect(safeRel(p)).toBeNull());

  it('64 segments are fine, 65 are not', () => {
    expect(safeRel(Array.from({ length: 64 }, () => 'a').join('/'))).not.toBeNull();
  });

  it('normalises harmless forms', () => {
    expect(safeRel('app/./Models//User.php')).toBe('app/Models/User.php');
    expect(safeRel('app/Http/../Models/User.php')).toBe('app/Models/User.php');
    expect(safeRel('vendor/acme/lib/src/Thing.php')).toBe('vendor/acme/lib/src/Thing.php');
    expect(safeRel('.hidden/x.ts')).toBe('.hidden/x.ts');
    expect(safeRel('console.php')).toBe('console.php'); // a device name only as a whole segment
  });

  it('safeJoin: no part may be absolute, and the result stays inside', () => {
    expect(safeJoin('app', 'Models/User.php')).toBe('app/Models/User.php');
    expect(safeJoin('', 'x.php')).toBe('x.php');
    expect(safeJoin('app', '/etc/passwd')).toBeNull();
    expect(safeJoin('app', '../../x')).toBeNull();
    expect(safeJoin('/abs', 'x')).toBeNull();
    expect(safeJoin('app', 'C:\\x')).toBeNull();
    expect(safeJoin('a/b', '../c')).toBe('a/c');
  });
});

describe('PSR-4 maps (parsed as text, never executed)', () => {
  it('composer.json: autoload + autoload-dev, string or list, nested composer root, vendor-dir', () => {
    const json = JSON.stringify({
      autoload: { 'psr-4': { 'App\\': 'app/', 'Lib\\': ['src/', 'lib'] }, files: ['x.php'] },
      'autoload-dev': { 'psr-4': { 'Tests\\': 'tests/' } },
      config: { 'vendor-dir': 'deps' },
    });
    const { map, vendorDir } = psr4FromComposer(json, 'backend/composer.json');
    expect(map).toEqual([
      { prefix: 'App\\', dirs: ['backend/app'] },
      { prefix: 'Lib\\', dirs: ['backend/src', 'backend/lib'] },
      { prefix: 'Tests\\', dirs: ['backend/tests'] },
    ]);
    expect(vendorDir).toBe('backend/deps');
    expect(psr4FromComposer('{ not json', 'composer.json')).toEqual({ map: [], vendorDir: 'vendor' });
  });

  it('composer.json attacks: escaping / absolute / odd directories and prefixes are dropped', () => {
    const json = JSON.stringify({
      autoload: {
        'psr-4': {
          'A\\': '../outside/',
          'B\\': '/etc/',
          'C\\': 'C:\\Windows\\',
          'D\\': ['ok/', 'x/../../../up'],
          'E\\': 'nul/',
          'F..\\': 'f/',
          'G\\': 42,
          'H\\': 'a\u0000b',
        },
      },
      config: { 'vendor-dir': '../../elsewhere' },
    });
    const { map, vendorDir } = psr4FromComposer(json, 'composer.json');
    expect(map).toEqual([{ prefix: 'D\\', dirs: ['ok'] }]);
    expect(vendorDir).toBeNull();
  });

  it('autoload_psr4.php: $vendorDir / $baseDir entries, escapes, several folders per prefix', () => {
    const php = `<?php
// autoload_psr4.php @generated by Composer
$vendorDir = dirname(__DIR__);
$baseDir = dirname($vendorDir);

return array(
    'Illuminate\\\\Support\\\\' => array($vendorDir . '/laravel/framework/src/Illuminate/Macroable', $vendorDir . '/laravel/framework/src/Illuminate/Support'),
    'Acme\\\\' => array($vendorDir . '/acme/lib/src'),
    'App\\\\' => array($baseDir . '/app'),
    'Quote\\\\' => array($vendorDir . '/it\\'s/src'),
);
`;
    expect(psr4FromAutoload(php, 'vendor/composer/autoload_psr4.php')).toEqual([
      { prefix: 'Illuminate\\Support\\', dirs: ['vendor/laravel/framework/src/Illuminate/Macroable', 'vendor/laravel/framework/src/Illuminate/Support'] },
      { prefix: 'Acme\\', dirs: ['vendor/acme/lib/src'] },
      { prefix: 'App\\', dirs: ['app'] },
      { prefix: 'Quote\\', dirs: ["vendor/it's/src"] },
    ]);
  });

  it('autoload_psr4.php attacks: traversal, absolute paths, other variables, code are ignored', () => {
    const php = `<?php
return array(
    'A\\\\' => array($vendorDir . '/../../../../etc'),
    'B\\\\' => array('/etc/passwd'),
    'C\\\\' => array(__DIR__ . '/x', system('rm -rf /') . '/y'),
    'D\\\\' => array($baseDir . '/../outside'),
    'E\\\\' => array($vendorDir . '/ok/src', $evil . '/x'),
    'F\\\\' => array($vendorDir . 'C:/Windows'),
    'G\\\\' => array($vendorDir . '/a\\\\..\\\\..\\\\b'),
);`;
    expect(psr4FromAutoload(php, 'vendor/composer/autoload_psr4.php')).toEqual([{ prefix: 'E\\', dirs: ['vendor/ok/src'] }]);
  });

  it('huge or crafted maps: linear to parse, capped (5,000 prefixes, 16 folders each), oversized files skipped', () => {
    const many = Array.from({ length: 20_000 }, (_, i) => `    'Ns${i}\\\\' => array($vendorDir . '/p${i}/src'),`).join('\n');
    const wide = `    'Wide\\\\' => array(${Array.from({ length: 200 }, (_, i) => `$vendorDir . '/w${i}'`).join(', ')}),`;
    let auto: ReturnType<typeof psr4FromAutoload> = [];
    const t0 = performance.now();
    auto = psr4FromAutoload(`<?php\nreturn array(\n${wide}\n${many}\n);`, 'vendor/composer/autoload_psr4.php');
    const entries: Array<[string, string[]]> = Array.from({ length: 20_000 }, (_, i) => [`C${i}\\`, ['a/', 'b/']]);
    entries.unshift(['Wide\\', Array.from({ length: 40 }, (_, k) => `d${k}/`)]);
    const json = JSON.stringify({ autoload: { 'psr-4': Object.fromEntries(entries) } }); // < 2 MB
    const { map } = psr4FromComposer(json, 'composer.json');
    expect(performance.now() - t0).toBeLessThan(1500);
    expect(auto).toHaveLength(5000);
    expect(auto[0]).toMatchObject({ prefix: 'Wide\\' });
    expect(auto[0].dirs).toHaveLength(16);
    expect(map).toHaveLength(5000);
    expect(map[0].dirs).toHaveLength(16);
    const big = JSON.stringify({ autoload: { 'psr-4': { 'App\\': 'app/' } }, pad: 'x'.repeat(3 << 20) });
    expect(psr4FromComposer(big, 'composer.json').map).toEqual([]);
    const ix = psr4Index([auto, map]);
    const t1 = performance.now();
    for (let i = 0; i < 64; i++) psr4Candidates(`Ns${i}\\Deep\\Name\\Space\\Thing`, ix);
    expect(performance.now() - t1).toBeLessThan(50); // a map lookup per namespace prefix, not a scan of 10,000 entries
    expect(psr4Candidates('Ns7\\A\\B', ix)).toEqual(['vendor/p7/src/A/B.php']);
  });

  it('candidates: longest prefix first, fallback prefix last, never outside, only PHP names', () => {
    const maps = [
      [
        { prefix: 'App\\', dirs: ['app'] },
        { prefix: 'App\\Models\\', dirs: ['models'] },
        { prefix: '', dirs: ['lib'] },
      ],
    ];
    expect(psr4Candidates('App\\Models\\User', maps)).toEqual(['models/User.php', 'app/Models/User.php', 'lib/App/Models/User.php']);
    expect(psr4Candidates('\\App\\Http\\Kernel', maps)).toEqual(['app/Http/Kernel.php', 'lib/App/Http/Kernel.php']);
    expect(psr4Candidates('App\\..\\..\\etc\\passwd', maps)).toEqual([]);
    expect(psr4Candidates('App\\Models/../../x', maps)).toEqual([]);
    expect(psr4Candidates('App\\C:', maps)).toEqual([]);
    expect(psr4Candidates('', maps)).toEqual([]);
  });
});

describe('import specifiers', () => {
  it('JS: relative only, extensions and index files, TS for .js, nothing outside', () => {
    expect(jsCandidates('src/app/main.ts', './util')).toEqual([
      'src/app/util.ts',
      'src/app/util.tsx',
      'src/app/util.d.ts',
      'src/app/util.js',
      'src/app/util.jsx',
      'src/app/util.mjs',
      'src/app/util.cjs',
      'src/app/util.vue',
      'src/app/util/index.ts',
      'src/app/util/index.tsx',
      'src/app/util/index.d.ts',
      'src/app/util/index.js',
      'src/app/util/index.jsx',
      'src/app/util/index.mjs',
      'src/app/util/index.cjs',
      'src/app/util/index.vue',
    ]);
    expect(jsCandidates('src/a.ts', '../lib/x.js')).toEqual(['lib/x.js', 'lib/x.ts', 'lib/x.tsx']);
    expect(jsCandidates('src/a.ts', './b.mjs?raw')).toEqual(['src/b.mjs', 'src/b.mts']);
    expect(jsCandidates('src/a.ts', 'react')).toEqual([]);
    expect(jsCandidates('src/a.ts', '@/x')).toEqual([]);
    expect(jsCandidates('src/a.ts', '../../../etc/passwd')).toEqual([]);
    expect(jsCandidates('src/a.ts', './..\\..\\x')).toEqual([]);
    expect(jsCandidates('src/a.ts', './C:/x')).toEqual([]);
    expect(jsCandidates('src/a.ts', './x\u0000.js')).toEqual([]);
    expect(jsCandidates('a.ts', '/etc/passwd')).toEqual([]);
  });

  it('Python: dots climb folders, never above the root', () => {
    expect(pyCandidates('pkg/sub/mod.py', { dots: 1, module: 'helpers' }, 'run')).toEqual(['pkg/sub/helpers.py', 'pkg/sub/helpers/__init__.py', 'pkg/sub/helpers/run.py', 'pkg/sub/helpers/run/__init__.py']);
    expect(pyCandidates('pkg/sub/mod.py', { dots: 2, module: '' }, 'util')).toEqual(['pkg/__init__.py', 'pkg/util.py', 'pkg/util/__init__.py']);
    expect(pyCandidates('mod.py', { dots: 3, module: 'x' }, 'y')).toEqual([]);
  });
});
